// Generates src/styles/tokens.css from docs/design/tokens.json (approved
// design). Run: npm run tokens (also part of npm run build).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(
  readFileSync(join(here, '..', '..', 'docs', 'design', 'tokens.json'), 'utf8'),
);

const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
const vars = (obj, prefix) =>
  Object.entries(obj)
    .map(([k, v]) => `  --${prefix}-${kebab(k)}: ${v};`)
    .join('\n');

const { light, dark } = tokens.color;
const palette = Object.entries(tokens.palette).filter(([k]) => !k.startsWith('$'));
const pal = (theme) =>
  Object.fromEntries(
    palette.flatMap(([name, c]) =>
      Object.entries(c[theme]).map(([k, v]) => [`${name}-${k}`, v]),
    ),
  );
// .pal-<name> sets --pal-solid/soft/text for a chip, stripe or dot.
const palClasses = palette
  .map(
    ([name]) =>
      `.pal-${name} {\n` +
      ['solid', 'soft', 'text'].map((k) => `  --pal-${k}: var(--pal-${name}-${k});`).join('\n') +
      '\n}',
  )
  .join('\n\n');
// The document sheet is always white: paper, ink and text colours are the light ones in both themes.
const sheet = {
  paper: light.surface,
  ink: light.text,
  ...Object.fromEntries(palette.map(([name, c]) => [name, c.light.text])),
};
const px = (n) => `${n}px`;
const radius = Object.fromEntries(Object.entries(tokens.radius).map(([k, v]) => [k, px(v)]));
const size = Object.fromEntries(Object.entries(tokens.size).map(([k, v]) => [k, px(v)]));
const space = Object.fromEntries(tokens.space.map((v, i) => [String(i + 1), px(v)]));
// --fs-<desktop px>: the interface font size; on a phone (narrower than 900 px) a smaller one.
const fontPhone = Object.entries(tokens.fontPhone).filter(([k]) => !k.startsWith('$'));
const fontDesktop = Object.fromEntries(fontPhone.map(([k]) => [k, px(k)]));
const fontSmall = Object.fromEntries(fontPhone.map(([k, v]) => [k, px(v)]));
const motion = Object.fromEntries(
  Object.entries(tokens.motion).filter(([, v]) => typeof v === 'string'),
);

const css = `/* Generated by scripts/tokens.mjs from docs/design/tokens.json. Do not edit. */
:root {
  color-scheme: light;
${vars(light, 'c')}
${vars(pal('light'), 'pal')}
${vars(sheet, 'sheet')}
${vars(radius, 'radius')}
${vars(size, 'size')}
${vars(space, 'space')}
${vars(motion, 'motion')}
${vars(fontDesktop, 'fs')}
  --font-body: '${tokens.font.body}', ${tokens.font.fallback};
  --font-heading: '${tokens.font.heading}', ${tokens.font.fallback};
}

:root[data-theme='dark'] {
  color-scheme: dark;
${vars(dark, 'c')}
${vars(pal('dark'), 'pal')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${vars(dark, 'c').replace(/^/gm, '  ')}
${vars(pal('dark'), 'pal').replace(/^/gm, '  ')}
  }
}

@media (max-width: 899px) {
  :root {
${vars(fontSmall, 'fs').replace(/^/gm, '  ')}
  }
}

${palClasses}

@media (prefers-reduced-motion: reduce) {
  :root {
    --motion-fast: 0ms;
    --motion-base: 0ms;
    --motion-slow: 0ms;
  }
}
`;
writeFileSync(join(here, '..', 'src', 'styles', 'tokens.css'), css);
console.log('tokens.css written');
